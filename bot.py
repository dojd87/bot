def route(key: str, data: dict):
    """Повертає (текст, кнопки) для ключа, оновлюючи стан користувача."""
    if key == "gcp":
        data.clear()

    if key in CURRENT_MAP:
        data["current"] = CURRENT_MAP[key]
        key = "mix"

    if key in MIX_MAP:
        data["mix"] = MIX_MAP[key]
        key = "zyn"
    if key == "mix_no":
        data["mix"] = "Ні"
        key = "iluma"  # Якщо НЕ міксує — переходимо напряму до IQOS ILUMA i

    if key in ("iluma", "levia", "fl_i"):
        data["device"] = "iluma"
    if key in ("bonds", "fl_b"):
        data["device"] = "bonds"

    if key == "recs":
        return recs_screen(data.get("device", "iluma"))

    text, buttons = S.get(key, S["menu"])

    if key == "zyn" and data.get("current"):
        cur, mix = data.get("current"), data.get("mix", "—")
        tip = f"📋 Клієнт: <b>{cur}</b> | Міксинг: <b>{mix}</b>\n"
        if cur == "Наші пристрої":
            tip += "➡️ Закрийте потребу споживача. Якщо міксує з вейпом — запропонуйте <b>LEVIA</b>.\n"
        elif cur == "Вейп" or mix == "Вейп":
            tip += "➡️ Після ZYN особливо акцентуйте <b>ILUMA i з LEVIA</b>.\n"
        text = tip + "\n" + text

    return text, buttons


